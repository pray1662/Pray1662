export function getMcheyneReadings(date, office) {
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  const key = `${month}-${day}`;
  if (key === '02-29') {
    return { first: null, second: null, note: 'The original M’Cheyne plan has no 29 February appointment. Use this as a catch-up day, or continue with 1 March tomorrow.' };
  }
  const readings = mcheynePlan[key];
  if (!readings) throw new Error(`No M’Cheyne readings found for ${key}`);
  const pair = office === 'morning' ? readings.slice(0, 2) : readings.slice(2, 4);
  return { first: pair[0], second: pair[1] };
}
